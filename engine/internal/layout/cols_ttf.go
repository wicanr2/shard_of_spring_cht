package layout

// 欄寬預算(發行版:20 px 開源向量字,半形約 10 px)。docs/spec/04 §5。
//
// ⚠ **這三個數字是版面推出來的,不是手感。** 另一套在 cols_eten.go
// (本機版的倚天 24×24 點陣字,半形 12 px)—— 換字型就換一整組,
// 因為「一行放得下幾個字」直接決定清單放不放得下。
//
// ⚠ 都是**上限不是目標**:超過就畫到框外,而畫到框外的字**照樣印得出來**,
// 只是壓在別的面板上 —— 沒有錯誤訊息,也沒有測試會紅,
// 只有一團看不懂的畫面(戰鬥的提示列就這樣壓著隊伍面板很久,拍截圖才看見)。
const (
	// MsgCols:訊息面板 340 px 扣兩側內距 16 → 308 px ÷ 10 = 30 欄。
	// **折行不截斷** —— 截掉的字看不出來,折行看得出來。
	MsgCols = 30
	// ViewCols:主視野 612 px 扣內距 → 580 px ÷ 10 = 58 欄。
	ViewCols = 58
	// PromptCols:提示列 992 px 扣內距 → 960 px ÷ 10 = 96 欄。
	PromptCols = 96
)
