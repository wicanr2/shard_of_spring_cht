// Ending 是通關曲,**18 段**,由迷宮事件目標 533(最終戰)的處理常式在
// 執行期組出來 —— `MAZEMOVE 0x131D0`–`0x132D2` 的 18 次 `INT 3F:61`
// 把這些片段複製進 `ds:92F2 + 4k`(docs/re/182 §2 有逐段對照表)。
//
// **順序就是目的位址的順序**;BASIC 的用法是 `PLAY A$ + B$ + …`,
// 所以設定(`L8`/`L2`/`O3`)與音名(`G`/`GA`/`BG`)交錯是正常的。
//
// ⚠ 後面幾段**沒有 `T`/`MB`** —— 它們沿用前面的狀態,
// 所以這 18 段要當成**一首曲子的續播**,用同一份 State 依序解。
//
// ⚠ 先前這裡是**10 段**,用「`0x04CBC`–`0x04DB0` 的位元組範圍」讀的 ——
// 少了 8 段,而且 `MB T108 O3 L8a` / `MB T108 O4 L4 EC` 兩段各多讀一個字元。
// **用位元組範圍撈「一批描述子指到的片段」會多吃相鄰資料、漏掉不相鄰的**,
// 而讀出來的東西是合法的 `PLAY` 語法,看不出哪裡不對(docs/re/182 §5)。
//
// ✅ 「這是通關曲」不再是位置上的推測 —— **組裝它的就是最終戰的處理常式**
// (docs/re/182 §4)。
